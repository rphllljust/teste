CREATE TABLE IF NOT EXISTS fiscal_documents (
  id text PRIMARY KEY,
  direction text NOT NULL,
  document_type text NOT NULL,
  number text NOT NULL,
  series text,
  access_key text,
  issued_on text NOT NULL,
  period text NOT NULL,
  customer_id text,
  supplier text,
  client_name text,
  cfop text,
  nature text,
  municipality text,
  tax_regime text,
  gross_amount integer NOT NULL,
  tax_base integer NOT NULL DEFAULT 0,
  iss_rate integer NOT NULL DEFAULT 0,
  iss_amount integer NOT NULL DEFAULT 0,
  icms_rate integer NOT NULL DEFAULT 0,
  icms_amount integer NOT NULL DEFAULT 0,
  ipi_amount integer NOT NULL DEFAULT 0,
  pis_amount integer NOT NULL DEFAULT 0,
  cofins_amount integer NOT NULL DEFAULT 0,
  withheld_amount integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'registered',
  source_reference text,
  billing_id text,
  receivable_id text,
  payable_id text,
  contract_id text,
  order_id text,
  notes text,
  attachment_reference text,
  integration_provider text NOT NULL DEFAULT 'manual',
  created_at text NOT NULL,
  updated_at text NOT NULL,
  actor_id text NOT NULL,
  request_hash text NOT NULL,
  correlation_id text NOT NULL,
  UNIQUE(actor_id, number, series, direction),
  CHECK(direction IN ('inbound','outbound','service')),
  CHECK(document_type IN ('invoice','service_invoice','receipt','other')),
  CHECK(status IN ('registered','cancelled','reversed')),
  CHECK(gross_amount >= 0 AND tax_base >= 0 AND iss_amount >= 0 AND icms_amount >= 0 AND ipi_amount >= 0 AND pis_amount >= 0 AND cofins_amount >= 0 AND withheld_amount >= 0)
);
CREATE INDEX IF NOT EXISTS fiscal_documents_actor_period ON fiscal_documents(actor_id, period, issued_on, id);
CREATE INDEX IF NOT EXISTS fiscal_documents_order ON fiscal_documents(actor_id, order_id, issued_on);
CREATE TABLE IF NOT EXISTS fiscal_document_events (
  id text PRIMARY KEY,
  document_id text NOT NULL REFERENCES fiscal_documents(id),
  action text NOT NULL,
  actor_id text NOT NULL,
  metadata text NOT NULL,
  created_at text NOT NULL,
  correlation_id text NOT NULL
);
CREATE INDEX IF NOT EXISTS fiscal_document_events_document ON fiscal_document_events(document_id, created_at, id);
